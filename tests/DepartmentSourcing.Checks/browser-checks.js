async page => {
    const base = 'http://127.0.0.1:5188';
    const proof = 'C:/Users/user/AppData/Local/Temp/stms-sourcing-review/request-cycle';
    let count = 0;
    const check = (ok, message) => { if (!ok) throw new Error(message); count++; };
    async function login(user, path) {
        await page.context().clearCookies();
        await page.goto(base + '/Auth/Login?returnUrl=' + encodeURIComponent(path));
        await page.getByLabel('Email', { exact: true }).fill(user + '@example.test');
        await page.getByLabel('Password', { exact: true }).fill('Preview-Only!4729');
        await page.getByRole('button', { name: 'Login', exact: true }).click();
        await page.waitForURL(base + path);
    }
    const title = 'Browser packaging request ' + Date.now();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await login('requester', '/Department/Create');
    await page.locator('#Title').fill(title);
    await page.locator('#Description').fill('Food-safe packaging needed for production.');
    await page.locator('#RequiredByDate').fill(new Date(Date.now() + 864000000).toISOString().slice(0, 10));
    await page.locator('[name="Items[0].ItemName"]').fill('Food-safe bags');
    await page.locator('[name="Items[0].Specifications"]').fill('Sealed packaging, 25 kg capacity');
    await page.locator('[name="Items[0].Quantity"]').fill('100');
    await page.locator('[name="Items[0].Unit"]').fill('bag');
    await page.locator('[name="Items[0].EstimatedUnitPrice"]').fill('2');
    await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
    await page.waitForURL(/\/Department\/Details\/\d+/);
    const id = page.url().split('/').pop();
    await page.getByRole('button', { name: 'Submit / Resubmit', exact: true }).click();
    check((await page.locator('body').innerText()).includes('Submitted'), 'Department submits real form');
    await login('officer', '/SourcingOfficer/Requests');
    await page.getByLabel('Request title or number').fill(title);
    await page.waitForFunction(text => document.querySelector('#request-results')?.innerText.includes(text), title);
    check((await page.locator('#request-results').innerText()).includes('Submitted'), 'Live queue contains submitted form');
    await page.goto(base + '/SourcingOfficer/RequestDetails/' + id);
    check(await page.getByRole('link', { name: 'Accept and create tender', exact: true }).isVisible(), 'Acceptance is actionable');
    await page.getByRole('button', { name: 'Start review', exact: true }).click();
    check((await page.locator('body').innerText()).includes('UnderReview'), 'Officer starts review');
    check(!(await page.locator('body').innerText()).includes('already been converted'), 'Review shows correct request state');
    await page.screenshot({ path: proof + '/desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: proof + '/mobile.png', fullPage: true });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Request review fits mobile');
    await page.getByLabel('Changes required', { exact: true }).fill('Please increase bags to 120 and confirm packaging.');
    await page.getByRole('button', { name: 'Return to department with message', exact: true }).click();
    check((await page.locator('body').innerText()).includes('Returned'), 'Formal return updates sourcing screen');
    check(await page.getByRole('link', { name: /Changes requested for/ }).count() === 1, 'Returned request exposes its linked conversation');
    await login('requester', '/Department/Details/' + id);
    check((await page.locator('body').innerText()).includes('Please increase bags to 120'), 'Department sees exact return reason');
    await page.getByRole('link', { name: 'Messages and clarification responses', exact: true }).click();
    await page.getByRole('link', { name: /Changes requested for/ }).first().click();
    check(await page.locator('textarea[name="response"]').isVisible(), 'Department can reply in its chat');
    await page.locator('textarea[name="response"]').fill('Confirmed. Updating to 120 bags.');
    await page.getByRole('button', { name: /Send/ }).click();
    check((await page.locator('body').innerText()).includes('Confirmed. Updating to 120 bags.'), 'Chat reply appears');
    await page.goto(base + '/Department/Details/' + id);
    await page.getByRole('link', { name: 'Edit', exact: true }).click();
    await page.locator('[name="Items[0].Quantity"]').fill('120');
    await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
    await page.getByRole('button', { name: 'Submit / Resubmit', exact: true }).click();
    check((await page.locator('body').innerText()).includes('Submitted'), 'Edited request resubmits');
    await login('officer', '/SourcingOfficer/RequestDetails/' + id);
    check((await page.locator('tbody').innerText()).includes('120'), 'Officer sees revised quantity');
    await page.getByRole('link', { name: 'Accept and create tender', exact: true }).click();
    check(await page.getByRole('button', { name: 'Accept and create draft', exact: true }).isVisible(), 'Acceptance uses shared tender form');
    await page.locator('#CategoryId').selectOption({ label: 'Food ingredients' });
    await page.locator('#SubmissionDeadline').fill(new Date(Date.now() + 432000000).toISOString().slice(0,16));
    await page.locator('#TermsAndConditions').fill('Food-safe sealed packaging. Deliver according to agreed schedule.');
    await page.locator('#ReviewComment').fill('Updated quantities confirmed.');
    await page.screenshot({ path: proof + '/accept-mobile.png', fullPage: true });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Acceptance fits mobile');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: proof + '/accept-desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Accept and create draft', exact: true }).click();
    await page.waitForURL(/\/SourcingOfficer\/Details\/\d+/);
    check((await page.locator('body').innerText()).includes('120'), 'Created tender contains revised item snapshot');
    check((await page.locator('body').innerText()).includes('Draft'), 'Acceptance creates draft before committee handoff');
    await page.goto(base + '/SourcingOfficer/RequestDetails/' + id);
    check(await page.getByRole('link', { name: 'Accept and create tender', exact: true }).count() === 0, 'Converted request hides duplicate acceptance');
    await login('requester', '/Department/Details/' + id);
    check((await page.locator('body').innerText()).includes('ConvertedToTender'), 'Department sees converted state');
    check(await page.getByRole('link', { name: 'Edit', exact: true }).count() === 0, 'Department cannot edit converted request');
    return { checks: count, requestId: id, result: 'Department → review → return/message → edit/resubmit → accept/draft passed' };
}
